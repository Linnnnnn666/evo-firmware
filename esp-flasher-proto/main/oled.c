void oled_text(uint8_t x, uint8_t y, const char *s) {
    if (y >= OLED_PAGES || !s) return;
    for (; *s && x <= OLED_W / 6 - 1; s++, x++) {
        uint8_t c = (uint8_t)(*s);
        if (c < 32 || c > 126) c = ' ';
        const uint8_t *g = FONT5X7[c - 32];
        uint8_t *dst = s_fb + y * OLED_W + x * 6;
        for (int col = 0; col < 5; col++) {
            dst[col] = g[col];
        }
        dst[5] = 0;  // 字符间距
    }
}

void oled_bar(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t pct) {
    if (y >= OLED_PAGES || pct > 100) return;
    uint8_t fill = (uint8_t)(w * pct / 100);
    for (uint8_t row = 0; row < h; row++) {
        uint8_t *dst = s_fb + (y + row) * OLED_W + x;
        for (uint8_t col = 0; col < w; col++) {
            dst[col] = (col < fill) ? 0xFF : 0x00;
        }
    }
}

