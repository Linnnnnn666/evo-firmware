// 16x16 简化：仅数字 0-9（状态用）。其余字符回落小字体。
void oled_big(uint8_t y, const char *s) {
    if (y >= OLED_PAGES - 1 || !s) return;
    uint8_t x = 0;
    for (; *s && x <= OLED_W / 8 - 2; s++, x += 8) {
        char c = *s;
        if (c >= '0' && c <= '9') {
            const uint8_t *g = FONT16[c - '0'];
            for (int row = 0; row < 2; row++) {
                uint8_t *dst = s_fb + (y + row) * OLED_W + x;
                for (int col = 0; col < 8; col++) {
                    dst[col] = g[row * 16 + col * 2];
                    dst[col + 128] = g[row * 16 + col * 2 + 1];
                }
            }
        } else {
            // 空格清掉 8x16 区域
            for (int row = 0; row < 2; row++) {
                uint8_t *dst = s_fb + (y + row) * OLED_W + x;
                memset(dst, 0, 8);
            }
        }
    }
}

// ---------- 中文 16x16 渲染（UTF-8）----------
// 中文占 16px 宽 2 页高；ASCII 回落 6x8（顶部对齐）
void oled_cn(uint8_t x, uint8_t y, const char *s) {
    if (y >= OLED_PAGES - 1 || !s) return;
    uint8_t px = x;
    while (*s && px <= OLED_W - 16) {
        unsigned char c = (unsigned char)*s;
        if (c >= 0xE0 && s[1] && s[2]) {
            // 3 字节 UTF-8 中文
            const uint8_t *g = cn_lookup(s[0], s[1]);
            if (g) {
                for (int row = 0; row < 2; row++) {
                    uint8_t *dst = s_fb + (y + row) * OLED_W + px;
                    for (int col = 0; col < 8; col++) {
                        dst[col] = g[row * 16 + col * 2];
                        dst[col + 8] = g[row * 16 + col * 2 + 1];
                    }
                }
                s += 3;
                px += 16;
                continue;
            }
            s += 3;  // 字库没有的字跳过
            continue;
        } else if (c >= 0x80) {
            s++;  // 半个 UTF-8 字节跳过
            continue;
        } else {
            // ASCII 6x8（顶部页）
            if (c < 32 || c > 126) c = ' ';
            const uint8_t *g = FONT5X7[c - 32];
            uint8_t *dst = s_fb + y * OLED_W + px;
            for (int col = 0; col < 5; col++) dst[col] = g[col];
            dst[5] = 0;
            s++;
            px += 6;
        }
    }
}

void oled_cn_line(uint8_t y, const char *s) {
    oled_cn(0, y, s);
}
