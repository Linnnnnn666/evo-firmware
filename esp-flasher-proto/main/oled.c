static const char *TAG = "oled";

#define OLED_ADDR   0x3C
#define OLED_W      128
#define OLED_H      64
#define OLED_PAGES  8   // 64/8

// I2C 引脚（N16R8 空闲引脚；可改）
#define I2C_PORT    I2C_NUM_0
#define I2C_SDA     8
#define I2C_SCL     9
#define I2C_FREQ    400000

static i2c_master_dev_handle_t s_dev = NULL;
static i2c_master_bus_handle_t s_bus = NULL;  // 保存总线句柄（防止生命周期问题）
static uint8_t s_fb[OLED_W * OLED_PAGES];  // 显示缓冲

// ---------- 底层 ----------
static void oled_cmd(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    if (s_dev) i2c_master_transmit(s_dev, buf, 2, 100);
}

static void oled_data(const uint8_t *data, uint32_t len) {
    if (!s_dev) return;
    uint8_t *buf = malloc(len + 1);
    if (!buf) return;
    buf[0] = 0x40;
    memcpy(buf + 1, data, len);
    i2c_master_transmit(s_dev, buf, len + 1, 100);
    free(buf);
}

// ---------- 初始化 ----------
bool oled_init(void) {
    i2c_master_bus_config_t bus_cfg = {
        .i2c_port = I2C_PORT,
        .sda_io_num = I2C_SDA,
        .scl_io_num = I2C_SCL,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    i2c_master_bus_handle_t bus = NULL;
    if (i2c_new_master_bus(&bus_cfg, &bus) != ESP_OK) {
        ESP_LOGE(TAG, "I2C 总线创建失败（SDA=%d SCL=%d）", I2C_SDA, I2C_SCL);
        return false;
    }
    s_bus = bus;
    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = OLED_ADDR,
        .scl_speed_hz = I2C_FREQ,
    };
    if (i2c_master_bus_add_device(bus, &dev_cfg, &s_dev) != ESP_OK) {
        ESP_LOGE(TAG, "OLED 设备添加失败");
        return false;
    }

    // SSD1306 初始化序列
    static const uint8_t init_seq[] = {
        0xAE,             // display off
        0xD5, 0x80,       // clock div
        0xA8, 0x3F,       // multiplex 1/64
        0xD3, 0x00,       // display offset
        0x40,             // start line 0
        0x8D, 0x14,       // charge pump on
        0x20, 0x00,       // horizontal memory mode
        0xA1,             // segment remap
        0xC8,             // COM scan dec
        0xDA, 0x12,       // COM pins
        0x81, 0xCF,       // contrast
        0xD9, 0xF1,       // precharge
        0xDB, 0x40,       // VCOM detect
        0xA4,             // display all on resume
        0xA6,             // normal display
        0xAF,             // display on
    };
    for (uint32_t i = 0; i < sizeof(init_seq); i++) {
        oled_cmd(init_seq[i]);
    }
    oled_clear();
    oled_show();
    ESP_LOGI(TAG, "OLED 初始化完成 (0x%02X, SDA=%d SCL=%d)", OLED_ADDR, I2C_SDA, I2C_SCL);
    return true;
}

// ---------- 缓冲操作 ----------
void oled_clear(void) {
    memset(s_fb, 0, sizeof(s_fb));
}

void oled_show(void) {
    for (uint8_t page = 0; page < OLED_PAGES; page++) {
        oled_cmd(0xB0 + page);  // page addr
        oled_cmd(0x00);         // col low
        oled_cmd(0x10);         // col high
        oled_data(s_fb + page * OLED_W, OLED_W);
    }
}

